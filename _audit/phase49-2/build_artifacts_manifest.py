def sha(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def line(rel):
    p = os.path.join(ROOT, rel.replace("/", os.sep))
    return "%s  %d  %s" % (sha(p), os.path.getsize(p), rel)


def main():
    ci_status = "PENDING"
    if os.path.exists(CI):
        rec = json.load(open(CI, encoding="utf-8"))
        ci_status = "%s commit %s" % (rec.get("status", "UNKNOWN"),
                                      rec.get("commit", "?"))
    ingest = json.load(open(os.path.join(ROOT, "_audit", "phase49-2", "evidence",
                                        "candle-ingest.json"), encoding="utf-8"))
    counts = ingest.get("counts") or {}
    out = [
        "# Phase 4.9.2 artifact SHA-256 manifest",
        "# generated by _audit/phase49-2/build_artifacts_manifest.py",
        "# generated_at: %s" % datetime.datetime.now(datetime.timezone.utc)
        .strftime("%Y-%m-%dT%H:%M:%SZ"),
        "# verdict: PHASE49.2_ACCEPTANCE_MET_FOR_30_SYMBOL_PILOT",
        "# ci_status: %s" % ci_status,
        "# independent_db_revision: %s" % ingest.get("revision", "?"),
        "# independent_db_rows: raw=%s adjusted=%s factors=%s" % (
            counts.get("reference_raw_rows", "?"),
            counts.get("reference_adjusted_rows", "?"),
            counts.get("adjustment_factors", "?")),
        "# format: sha256  size_bytes  path",
        "# section: 1=deliverables 2=ledgers/evidence 3=mission scripts 4=code and gates 5=inputs (not committed)",
    ]
    for header, group in (("1", DELIVERABLES), ("2", EVIDENCE),
                          ("3", SCRIPTS), ("4", CODE)):
        out.append("# --- section %s ---" % header)
        out.extend(line(rel) for rel in group)
    out.append("# --- section 5 (sha256, size, note) ---")
    missing = []
    for rel, note in INPUTS:
        p = os.path.join(ROOT, rel.replace("/", os.sep))
        if os.path.exists(p):
            out.append("%s  %d  %s  # %s" % (sha(p), os.path.getsize(p), rel, note))
        else:
            missing.append(rel)
            out.append("%s  -  %s  # %s (absent on this host)" % ("0" * 64, rel, note))
    text = "\n".join(out) + "\n"
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote", OUT)
    print("deliverables=%d evidence=%d scripts=%d code=%d inputs=%d missing_inputs=%s"
          % (len(DELIVERABLES), len(EVIDENCE), len(SCRIPTS), len(CODE),
             len(INPUTS), missing or "none"))


if __name__ == "__main__":
    main()
