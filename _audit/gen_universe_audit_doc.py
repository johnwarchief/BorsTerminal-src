def fa(x):
    s = f"{x:,}" if isinstance(x, int) and abs(x) >= 1000 else str(x)
    out = []
    for ch in s:
        if ch.isdigit():
            out.append(FA[int(ch)])
        elif ch == ",":
            out.append("٬")
        elif ch == "-":
            out.append("−")
        elif ch == ".":
            out.append("٫")
        else:
            out.append(ch)
    return "".join(out)


def sh(cmd):
    try:
        r = subprocess.run(cmd, shell=True, cwd=ROOT, capture_output=True,
                           text=True, encoding="utf-8", errors="replace", timeout=60)
        return (r.stdout or "").strip()
    except Exception as ex:
        return "(not read: %s)" % type(ex).__name__


def num(path, key=None):
    d = json.load(io.open(path, encoding="utf-8"))
    return d if key is None else d.get(key)


def guard_line(path, needle):
    """آخرینِ خطِ شمارشِ یکِ گارد (تفکیکِ الگوها درِ dev/guard_counts.py است)"""
    if not os.path.exists(path):
        return None
    for ln in reversed(io.open(path, encoding="utf-8", errors="replace").read().splitlines()):
        if needle in ln:
            return ln.strip()
    return None


