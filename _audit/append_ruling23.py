# -*- coding: utf-8 -*-
"""رأیِ ۲۳ (دورِ J) را به OWNER_RULINGS می‌افزاید — رقم‌ها از codepoint."""
import io

P = "docs/fts-notes/OWNER_RULINGS.md"
FA = "".join(chr(0x06F0 + d) for d in range(10))


def N(x):
    return "".join(FA[int(c)] for c in str(int(x)))


n = N(23)
d1, d2, d3 = N(1405), N(7), N(12)
block = """
## رأیِ %(n)s — جت فقط کندلِ آخر؛ taxonomyِ تک‌منبع؛ وضعیت از موتور، نه از رابط (%(d1)s/%(d2)s/%(d3)s)

دورِ J (بهینه‌سازیِ موتورِ تکنیکال و نمایشِ واقعیِ سیگنال‌ها). مالک چهار چیز را تکلیف کرد:

۱) **جت درِ production فقط برایِ `candles[-1]` محاسبه و منتشر می‌شود.** هیچ مسیرِ
برنامه‌ای (تحلیلِ تک‌نماد، اسکرینر، بج، سایدبار، چارت) نباید مارکرِ جتِ تاریخی بسازد؛
`_fts_setup_history` دیگر جت نمی‌کارد — حتی اگر payloadِ کهنه چنین رویدادی بیاورد،
چارت رسمش نمی‌کند. محاسبهٔ جت رویِ هر کندل **فقط** درِ `tools/fts_signal_lab.py`
(پژوهشِ تاریخی) مجاز است و با production قاطی نمی‌شود. سطحِ مقاومت/سقف context است.

۲) **نقطه‌زنی دو چیز است، نه یکی:** `floor/floor_date` اطلاعاتِ ساختاریِ کانال است و
`trigger_date` کندلی که لمس + ریباند رویِ آن رخ داده. مارکرِ خرید رویِ کندلِ تریگر
می‌نشیند، نه رویِ لنگرِ کف.

۳) **فیبو context است، نه تریگر.** داخلِ باند بودن نه امتیازِ ورود می‌گیرد، نه
`technicalSignal` را صعودی می‌کند، نه درِ رابط «سیگنال/نقطه‌زنی» خوانده می‌شود؛ برچسبش
«موقعیت فیبو» است و سطوح/کمربندها برایِ تحلیل رویِ چارت می‌مانند (سطح‌هایِ هفتگانه
پیش‌فرض رسم نمی‌شوند تا کندل عنصرِ اصلی بماند). قاعدۀ ۰٫۵ و تعریفِ leg دست‌نخورده
و مستند می‌ماند؛ خودسرانه حل نشد.

۴) **یک taxonomy و یک اولویتِ وضعیت.** `entry / context / warning / exit` درِ خودِ موتور
تعریف و منتشر می‌شود (`roles`) و متنِ وضعیت از `_fts_status_block` با همین اولویت:
حدِ ضرر ← خروجِ تأییدشده ← وتوی هفتگی ← تریگرِ امروز ← هشدار ← فقطِ زمینه ← بی‌سیگنال
← بی‌داده. کامپوننت حق ندارد وضعیت را با رشتهٔ ثابتی مثلِ «در انتظار شکست خط آبی»
توضیح دهد، و وتوی هفتگی با «پرواز فعال» هم‌زمان منتشر نمی‌شود.

ضمناً: «داده نیست» هیچ‌جا `false` نمی‌شود — لایه‌هایِ خروجِ L1..L4 هم سه‌حاله‌اند و
verdictِ بی‌داده `unknown` است نه `hold`. Warning هرگز Confirmed Exit خوانده نمی‌شود.
%(d1)s/%(d2)s/%(d3)s.
""" % {"n": n, "d1": d1, "d2": d2, "d3": d3}

t = io.open(P, encoding="utf-8", newline="").read()
assert "چنان" not in t  # noqa
t = t.rstrip("\r\n") + "\r\n" + block.replace("\n", "\r\n")
io.open(P, "w", encoding="utf-8", newline="").write(t)
print("appended رأیِ " + n)
