def N(x, sep=False):
    s = ("{:,}".format(int(x))) if sep else str(int(x))
    return "".join("\u066c" if c == "," else chr(0x06F0 + int(c)) for c in s
                   if c.isdigit() or c == ",")


def D(x, digits=3):
    return "".join("\u066b" if c == "." else chr(0x06F0 + int(c))
                   for c in ("%.*f" % (digits, x)))


