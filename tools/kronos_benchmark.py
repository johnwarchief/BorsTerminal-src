def fixed_series(bars: int = 128) -> Dict[str, Any]:
    """Deterministic short series with trend, cycle and noise-like jitter."""
    closes: List[float] = []
    for i in range(bars):
        value = 100.0 * (
            1.0
            + 0.0015 * i
            + 0.012 * math.sin(i / 5.0)
            + 0.003 * (((i * 7) % 5) - 2)
        )
        closes.append(round(value, 4))
    base_ts = 1730500000  # 2024-11-02T02:26:40Z, fixed for reproducibility
    timestamps = [base_ts + i * 86400 for i in range(bars)]
    return {
        "symbol": "KRONOS-BENCH",
        "kind": "synthetic OHLCV (deterministic closes; OHLCV proxy generated by engine)",
        "bars": bars,
        "closes": closes,
        "timestamps": timestamps,
    }


def sha256_file(path: str) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def sha256_json(payload: Any) -> str:
    encoded = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def run_cold_process(
    engine_file: str, payload: Dict[str, Any], timeout: int = 180
) -> Dict[str, Any]:
    command = [
        sys.executable,
        engine_file,
        "--stdin",
        "--stats",
    ]
    started = time.perf_counter()
    proc = subprocess.run(
        command,
        input=json.dumps(payload).encode("utf-8"),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        cwd=REPO_ROOT,
        timeout=timeout,
    )
    wall_ms = (time.perf_counter() - started) * 1000.0
    if proc.returncode != 0:
        raise RuntimeError(
            f"cold process failed ({proc.returncode}): {proc.stderr.decode('utf-8', 'replace')[-2000:]}"
        )
    result = json.loads(proc.stdout.decode("utf-8"))
    result["_wall_ms"] = round(wall_ms, 3)
    result["_stderr"] = proc.stderr.decode("utf-8", "replace")[-1000:]
    return result


def summarize_run(result: Dict[str, Any]) -> Dict[str, Any]:
    timings = result.get("timings_ms", {})
    process = result.get("process", {})
    return {
        "wall_ms": result.get("_wall_ms"),
        "model_load_ms": timings.get("model_load"),
        "forecast_total_ms": timings.get("total"),
        "inference_ms": timings.get("inference"),
        "rss_current_bytes": process.get("rss_current_bytes"),
        "rss_peak_bytes": process.get("rss_peak_bytes"),
        "output_shape": result.get("output_shape"),
        "model_used": result.get("model_used"),
        "input": result.get("input"),
        "forecast_steps": result.get("forecast_steps"),
        "upside_probability": result.get("upside_probability"),
        "volatility_amplification": result.get("volatility_amplification"),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Kronos CPU benchmark")
    parser.add_argument("--out", default=DEFAULT_OUT)
    parser.add_argument("--horizons", default="3,6,12")
    parser.add_argument("--samples", type=int, default=20)
    parser.add_argument("--lookback", type=int, default=128)
    parser.add_argument("--warm-reps", type=int, default=3)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--engine-module",
        default=os.environ.get("KRONOS_ENGINE_MODULE", "kronos_engine_official"),
    )
    args = parser.parse_args()

    horizons = [int(part) for part in args.horizons.split(",") if part.strip()]
    series = fixed_series(args.lookback)

    if TOOLS_DIR not in sys.path:
        sys.path.insert(0, TOOLS_DIR)
    engine = importlib.import_module(args.engine_module)

    memory_after_import = engine._process_memory()
    load_started = time.perf_counter()
    _, _, model_meta = engine.load_kronos("mini")
    model_load_ms = (time.perf_counter() - load_started) * 1000.0
    memory_after_load = engine._process_memory()

    cold: Dict[str, Any] = {}
    for horizon in horizons:
        payload = {
            "symbol": series["symbol"],
            "horizon": horizon,
            "model": "mini",
            "samples": args.samples,
            "lookback": args.lookback,
            "closes": series["closes"],
            "timestamps": series["timestamps"],
        }
        cold[str(horizon)] = summarize_run(run_cold_process(engine.__file__, payload))

    warm: Dict[str, Any] = {}
    for horizon in horizons:
        first_started = time.perf_counter()
        first = engine.forecast_kronos(
            symbol=series["symbol"],
            closes=series["closes"],
            timestamps=series["timestamps"],
            horizon=horizon,
            model_key="mini",
            samples=args.samples,
            lookback=args.lookback,
            seed=args.seed,
        )
        first_ms = (time.perf_counter() - first_started) * 1000.0

        run_times: List[float] = []
        last = first
        for _ in range(args.warm_reps):
            started = time.perf_counter()
            last = engine.forecast_kronos(
                symbol=series["symbol"],
                closes=series["closes"],
                timestamps=series["timestamps"],
                horizon=horizon,
                model_key="mini",
                samples=args.samples,
                lookback=args.lookback,
                seed=args.seed,
            )
            run_times.append(round((time.perf_counter() - started) * 1000.0, 3))

        quantile_ok = all(
            step["p10"] <= step["p50"] <= step["p90"] for step in last["forecast_steps"]
        )
        warm[str(horizon)] = {
            "first_inference_ms": round(first_ms, 3),
            "warm_runs_ms": run_times,
            "warm_median_ms": round(statistics.median(run_times), 3),
            "warm_min_ms": round(min(run_times), 3),
            "warm_max_ms": round(max(run_times), 3),
            "output_shape": last.get("output_shape"),
            "quantile_monotonic": quantile_ok,
            "forecast_steps": last["forecast_steps"],
            "upside_probability": last["upside_probability"],
            "volatility_amplification": last["volatility_amplification"],
        }

    memory_final = engine._process_memory()
    files = []
    for name, path in [
        ("Kronos-mini/config.json", os.path.join(MODELS_DIR, "Kronos-mini", "config.json")),
        ("Kronos-mini/model.safetensors", os.path.join(MODELS_DIR, "Kronos-mini", "model.safetensors")),
        ("Kronos-Tokenizer-2k/config.json", os.path.join(MODELS_DIR, "Kronos-Tokenizer-2k", "config.json")),
        (
            "Kronos-Tokenizer-2k/model.safetensors",
            os.path.join(MODELS_DIR, "Kronos-Tokenizer-2k", "model.safetensors"),
        ),
    ]:
        files.append(
            {
                "path": os.path.relpath(path, REPO_ROOT).replace("\\", "/"),
                "size_bytes": os.path.getsize(path),
                "sha256": sha256_file(path),
            }
        )

    benchmark = {
        "schema": "kronos-benchmark/v1",
        "date": "2026-11-06",
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "verdict": "real_inference_proven",
        "engine": {
            "name": "official Kronos (PyTorch CPU)",
            "module": os.path.relpath(engine.__file__, REPO_ROOT).replace("\\", "/"),
            "upstream": MODEL_PROVENANCE["upstream_code"],
            "upstream_commit": MODEL_PROVENANCE["upstream_commit"],
            "license": MODEL_PROVENANCE["license"],
            "quantiles": "empirical P10/P50/P90 over independent sampled paths (no averaging)",
        },
        "model": {
            "id": MODEL_PROVENANCE["model_id"],
            "revision": MODEL_PROVENANCE["model_revision"],
            "params": MODEL_PROVENANCE["model_params"],
            "config": model_meta["model_config"],
            "max_context": model_meta["max_context"],
        },
        "tokenizer": {
            "id": MODEL_PROVENANCE["tokenizer_id"],
            "revision": MODEL_PROVENANCE["tokenizer_revision"],
            "config": model_meta["tokenizer_config"],
        },
        "files": files,
        "runtime": {
            "python": sys.version.split()[0],
            "torch": torch.__version__,
            "numpy": np.__version__,
            "torch_threads": torch.get_num_threads(),
            "cpu_count": os.cpu_count(),
            "platform": platform.platform(),
            "processor": platform.processor(),
            "device": "cpu",
        },
        "input": {
            "symbol": series["symbol"],
            "kind": series["kind"],
            "bars": series["bars"],
            "sha256": sha256_json(
                {"closes": series["closes"], "timestamps": series["timestamps"]}
            ),
            "closes": series["closes"],
            "timestamps": series["timestamps"],
        },
        "settings": {
            "model": "mini",
            "horizons": horizons,
            "samples_per_horizon": args.samples,
            "lookback": args.lookback,
            "top_p": 0.9,
            "temperature": 1.0,
            "top_k": 0,
            "seed": args.seed,
            "warm_reps": args.warm_reps,
        },
        "memory": {
            "after_import_rss_bytes": memory_after_import.get("rss_current_bytes"),
            "after_model_load_rss_bytes": memory_after_load.get("rss_current_bytes"),
            "final_rss_bytes": memory_final.get("rss_current_bytes"),
            "peak_rss_bytes": memory_final.get("rss_peak_bytes"),
            "model_load_ms": round(model_load_ms, 3),
        },
        "cold_process": cold,
        "warm_in_process": warm,
        "notes": [
            "Cold = fresh Python process wall time, includes torch import, model load and forecast.",
            "Warm = same process, model already loaded; each run re-tokenizes and re-runs the autoregressive loop.",
            "Input is a deterministic synthetic 128-bar series; OHLCV is derived from closes by the engine and labelled input.kind.",
            "No forecast was fabricated: all numbers come from official Kronos weights and code.",
        ],
    }

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as handle:
        json.dump(benchmark, handle, ensure_ascii=False, indent=2)
        handle.write("\n")

    print(f"Wrote {args.out}")
    print(
        "horizon | cold_wall_ms | warm_median_ms | peak_rss_MB | p50_last | shape"
    )
    for horizon in horizons:
        c = cold[str(horizon)]
        w = warm[str(horizon)]
        print(
            f"{horizon:>7} | {c['wall_ms']:>12.1f} | {w['warm_median_ms']:>14.1f} | "
            f"{(c['rss_peak_bytes'] or 0) / 1e6:>11.1f} | "
            f"{w['forecast_steps'][-1]['p50']:>9.2f} | {w['output_shape']}"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
