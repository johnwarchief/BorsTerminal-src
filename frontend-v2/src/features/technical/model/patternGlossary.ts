export function getPatternExplanation(patternName: string): PatternEducationItem {
  if (PATTERN_EDUCATION_MAP[patternName]) {
    return PATTERN_EDUCATION_MAP[patternName];
  }
  const isBull = !patternName.toLowerCase().includes('bear') && !patternName.toLowerCase().includes('star');
  return {
    id: patternName,
    nameFa: patternName,
    isBullish: isBull,
    typeFa: isBull ? 'الگوی صعودی' : 'الگوی نزولی',
    psychologyFa: `الگوی تکنیکال ${patternName} نشان‌دهنده واکنش معامله‌گران به سطوح عرضه و تقاضا است.`,
    adviceFa: 'بررسی هم‌زمان با روند کلی و سطوح حمایت و مقاومت کلیدی.',
  };
}
