/**
 * R-UNSLOP-7 · مرزِ نمایشِ نامِ صنعت.
 *
 * رشته‌های خامِ صنعت از TSETMC با املائِ عربی و بی‌فاصله می‌آیند
 * («بيمه وصندوق بازنشستگي به جزتامين اجتماعي»). این کمکیِ خالص، فقط برایِ
 * **نمایش** آن‌ها را فارسی می‌کند؛ هیچ‌جا برایِ کلید، فیلتر، مقایسه، درخواستِ
 * API یا ستونِ CSV استفاده نمی‌شود، پس ارزشِ خامِ داده هرگز عوض نمی‌شود.
 *
 * ملاکِ اصلاح‌ها فقط رشته‌هایِ واقعیِ همان فید (۴۶ صنعتِ زنده) است و تنها املا
 * و فاصله ساخته می‌شود — هیچ واژهٔ تازه‌ای اختراع نمی‌شود.
 */

/** نگاشتِ مکانیکیِ حرفِ عربی به هجیِ فارسی (هیچ واژه‌ای عوض نمی‌شود). */
const LETTERS: Array<[RegExp, string]> = [
  [/ي/g, 'ی'], // ARABIC YEH → FARSI YEH
  [/ك/g, 'ک'], // ARABIC KAF → KEHEH
  [/ى/g, 'ی'], // ALEF MAKSURA → FARSI YEH
];

/**
 * اصلاح‌هایِ هدفمندِ چسبیده/بی‌فاصله؛ هر ورودی از رشتهٔ واقعیِ فید آمده و
 * پس از نگاشتِ حروف اعمال می‌شود. «به جزتامين» همان غلطِ معروفِ فید است.
 */
const SPELLING: Array<[RegExp, string]> = [
  [/وصندوق/g, 'و صندوق'],
  // پس از نگاشتِ حروف «به جزتامين» به «به جزتامین» می‌چسبد؛ شکلِ فارسی «به جزِ تأمین» است.
  [/جزتامین/g, 'جزِ تأمین'],
  [/بخاروآب/g, 'بخار و آب'],
  [/کی ونوری/g, 'کی و نوری'],
];

/**
 * نیم‌فاصلهٔ ضمیرِ جمع وقتی به واژه چسبیده است («بانكها» → «بانک‌ها»،
 * «فعاليتهاي» → «فعالیت‌های»). قاعده فقط جایی می‌نشیند که «ها/های»
 * بی‌فاصله پشتِ یک حرف آمده و بعدش فاصله یا پایانِ رشته است.
 */
const PLURAL_HAY = /([\u0621-\u06EF])های(?=[\s،]|$)/g;
const PLURAL_HA = /([\u0621-\u06EF])ها(?=[\s،]|$)/g;

/** نامِ صنعت برایِ نمایشِ فارسی؛ ورودیِ تهی/غیررشته رشتهٔ خالی می‌ماند. */
export function faSectorName(value: string | null | undefined): string {
  if (typeof value !== 'string' || value === '') return value ?? '';
  let out = value;
  for (const [pattern, replacement] of LETTERS) out = out.replace(pattern, replacement);
  for (const [pattern, replacement] of SPELLING) out = out.replace(pattern, replacement);
  out = out.replace(/،(?=\S)/g, '، ');
  out = out.replace(PLURAL_HAY, '$1‌های');
  out = out.replace(PLURAL_HA, '$1‌ها');
  return out.replace(/[ \t]{2,}/g, ' ').trim();
}
