def main():
    ok = fail = 0
    for title, want in CASES:
        got = notice_kind(title)
        good = got == want
        ok, fail = (ok + 1, fail) if good else (ok, fail + 1)
        print("  %s  %-62s انتظار=%-8s دریافت=%s"
              % ("✓" if good else "✗", title[:62], want, got))
    print("\n%d/%d passed" % (ok, len(CASES)))
    # قاعدهٔ کلیدی: هیچ عنوانی نباید همزمان هر دو باشد، و هیچ عنوانِ دلخواه
    # نباید به نوعِ دیگر اشتباه کند
    for title, want in CASES:
        assert notice_kind(title) == want, "parity broken on: " + title
    return 0 if fail == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
