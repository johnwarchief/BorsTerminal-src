#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate docs/opportunity-center/phase49/PYTHON-CI-MIGRATION.md from the registry.

The migration table is the registry, row for row: this script is the only writer,
so the document cannot drift from dev/suite_registry.json. Run with --check in CI
to fail when the committed document is stale.
"""
from __future__ import annotations

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REGISTRY = os.path.join(ROOT, "dev", "suite_registry.json")
EVIDENCE = os.path.join(ROOT, "_audit", "phase49-full-verification", "evidence", "ci-failures.json")
DOC = os.path.join(ROOT, "docs", "opportunity-center", "phase49", "PYTHON-CI-MIGRATION.md")
REL_EVIDENCE = "../../../_audit/phase49-full-verification/evidence"


def load():
    reg = json.load(open(REGISTRY, encoding="utf-8"))["suites"]
    evidence = []
    if os.path.isfile(EVIDENCE):
        evidence = json.load(open(EVIDENCE, encoding="utf-8"))
    return reg, evidence


def counts(reg):
    out = {}
    for e in reg.values():
        key = (e["category"], e["disposition"], e["profile"])
        out[key] = out.get(key, 0) + 1
    return out


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def build(reg, evidence):
    c = counts(reg)
    total = len(reg)
    a = sum(v for k, v in c.items() if k[0] == "A")
    b = sum(v for k, v in c.items() if k[0] == "B")
    cc = sum(v for k, v in c.items() if k[0] == "C")
    d = sum(v for k, v in c.items() if k[0] == "D")
    migrate = sum(v for k, v in c.items() if k[1] == "MIGRATE")
    deprecate = sum(v for k, v in c.items() if k[1] == "DEPRECATE")
    remove = sum(v for k, v in c.items() if k[1] == "REMOVE")
    keep = sum(v for k, v in c.items() if k[1] == "KEEP")

    lines = []
    add = lines.append
    add("# Python CI migration - Phase 4.9.1 (Task A4)")
    add("")
    add("Generated by `python dev/build_python_ci_migration_doc.py --write` from")
    add("`dev/suite_registry.json` and `_audit/phase49-full-verification/evidence/ci-failures.json`.")
    add("Do not hand-edit this file: `--check` fails when it is stale.")
    add("")
    add("Branch: `mission/phase49-full-verification-python-ci-2026-11-10`.")
    add("")
    add("## 1. Registry at a glance")
    add("")
    add("| Measure | Count |")
    add("| --- | ---: |")
    add("| Suites in the runner (`SUITES` + `JS_SUITES`) | %d |" % total)
    add("| A - live product/data contract | %d |" % a)
    add("| B - data / research / CI-tooling guard | %d |" % b)
    add("| C - legacy Python backend, API, UI or build surface | %d |" % cc)
    add("| D - obsolete, checked code deleted | %d |" % d)
    add("| KEEP | %d |" % keep)
    add("| MIGRATE (named Go/TS test owns the behaviour) | %d |" % migrate)
    add("| DEPRECATE (legacy lane, named owner, retirement 2026-11-10) | %d |" % deprecate)
    add("| REMOVE (deleted code) | %d |" % remove)
    add("")
    add("Category = what the suite exercises. Disposition = what happens to it.")
    add("A/B keep the Python harness (`KEEP`, profiles `production`/`data`); C/D live in the")
    add("`legacy` profile and carry either a real equivalence (`MIGRATE`) or a reason plus a")
    add("retirement date (`DEPRECATE`).")
    add("")
    add("**D = 0 is a measured result, not an omission.** Every remaining suite was parsed with")
    add("`ast`: every local module it imports exists at HEAD, and every imported symbol exists")
    add("in that module (0 missing modules, 0 missing symbols across the 221 rows). The suites")
    add("that reference retired v1 artefacts point at files that are still in the repository")
    add("(`archive/legacy_static/*`, `frontend/*`); no suite checks code that was deleted, and")
    add("`run_all_tests.py` is untouched, so no suite was dropped. `REMOVE` is therefore unused.")
    add("")
    add("## 2. Three-lane CI target")
    add("")
    add("| Lane | Workflow (Task A5) | Selection | Gate | Contents |")
    add("| --- | --- | --- | --- | --- |")
    add("| Production | `guards.yml` | no Python suite | blocking | Go (`go-backend`, `go-race`, `go-windows`), `frontend-v2`, `delivery-contract`, `data-integrity` (A only), `repo-hygiene`, `zero-python-runtime` |")
    add("| Data / tooling | `python-tooling.yml` | `python dev/run_all_tests.py --profile data` | blocking for data and tooling | %d B suites (data contracts, fixture oracles, stdlib tooling guards) |" % b)
    add("| Legacy | `python-legacy.yml` | `python dev/run_all_tests.py --profile legacy` | `continue-on-error: true` (report-only) | %d C suites (MIGRATE until retired + DEPRECATE) |" % cc)
    add("")
    add("`python-guards` and `js-syntax` leave the production gate; the legacy lane keeps them")
    add("visible without blocking a release. The registry guard (`dev/suite_registry_guard.py`)")
    add("runs in both Python lanes and fails the lane when a suite has no category, no")
    add("disposition, or a `MIGRATE` row whose Go/TS test does not exist.")
    add("")
    add("## 3. Zero-Python runtime proof plan")
    add("")
    add("1. **Bundle** - `cmd/bundlecheck` (A7) scans the shipped tree for Python extensions,")
    add("   `_internal`, `site-packages` and PyInstaller markers, and requires the Go bundle")
    add("   components (`BorsTerminal_Ultimate.exe`, `BorsTerminal_Shell.exe`,")
    add("   `frontend/index.html`, `Version.txt`).")
    add("2. **Process tree** - `cmd/runtimecheck` (A6) starts `borsd` with a temp")
    add("   `BORS_DATA_DIR`, reads `/api/health`, enumerates the process tree and proves no")
    add("   `python`/`py`/`pythonw`/`libpython` is present; it kills only its own PID and")
    add("   writes a JSON artifact.")
    add("3. **Installer** - `delivery-contract` installs the built setup into a runner temp")
    add("   directory (never the real install/registry), scans the installed tree for Python")
    add("   artefacts, runs `runtimecheck` against the installed EXE, then uninstalls (A8).")
    add("4. **Wiring and evidence** - A5 adds the `zero-python-runtime` job and the installer")
    add("   proof; A9 records the final workflow results. Python stays CI data/build tooling")
    add("   only; it is never part of the product runtime.")
    add("")
    add("## 4. Failure accounting")
    add("")
    add("The plan counts 24 failures in the `python-guards` annotation. `gh` is not installed")
    add("on this machine, so the annotation itself could not be read; the 24 rows below are the")
    add("**16 failures Task A3 root-caused** plus **the first eight additional FAILED labels of")
    add("the tracked CI capture `_audit/ci_guards_log.txt`** (in capture order), each")
    add("re-measured here through `dev/run_all_tests.py --only`. Every row links to a tracked")
    add("excerpt; the ignored `logs/*.log` files are never the citation.")
    add("")
    add("| # | Suite | Status | Cat/Disp | Error (measured) | Evidence |")
    add("| ---: | --- | --- | --- | --- | --- |")
    for i, row in enumerate(evidence, 1):
        add("| %d | `%s` | %s | %s/%s | %s | [excerpt](%s/%s) |" % (
            i, row["suite"], row["status"], row["category"], row["disposition"],
            cell(row["error"])[:220], REL_EVIDENCE,
            os.path.basename(row["evidence"])))
    add("")
    add("Statuses: `MEASURED_FAIL` = reproduced here (the failure is real); `NOT_MEASURED` =")
    add("the only failing section needs a dependency this machine cannot install")
    add("(`fastapi`/`requests`/`httpx`, no PyPI route); `NAMED_SKIP` = the runner reports a")
    add("named SKIP for a gitignored fixture (never a silent green); `FIXED_IN_A4` = the test")
    add("is green after the A4 fix.")
    add("")
    add("### Carried defects fixed in A4")
    add("")
    add("1. **B4 raw SQLite sha256 comparator** (`dev/test_fundamental_fixture_b4.py`). The")
    add("   committed-vs-fresh check hashed the whole file, including the SQLite header")
    add("   (bytes 96-99 = `SQLITE_VERSION_NUMBER`) and page layout, so a logically identical")
    add("   fixture failed on any other SQLite build. The comparator now compares the")
    add("   `sqlite_master` DDL plus every table's full row multiset, value-exact")
    add("   (`logical_db`/`logical_diff`), and the two-build byte-determinism check is")
    add("   unchanged. Before: `FAIL committed fixture equals a fresh build`")
    add("   (fresh `14dda855c5c1a57c`/`e2fe8dccad41994c` vs committed")
    add("   `7cee7d1cf4fc132e`/`18f3ac1bfb6c0d6b`). After: `PASS committed fixture equals a")
    add("   fresh build (schema + every row)` - 22 tables / 6,480 rows compared; a header-only")
    add("   probe (version `3050004` -> `3999999`) leaves the logical diff empty while the raw")
    add("   sha256 differs. No fixture byte and no golden was edited.")
    add("2. **Stale `NAME:LINE` citations** (`docs/FTS-RULE-ALGORITHM-MAP.md`).")
    add("   `_fts_analyze_candles:5603` -> `5610`, `_fts_jet_setup:4581` -> `4588`,")
    add("   `_fts_analyze_symbol:6011` -> `6018`, matching the real `def` lines in")
    add("   `api/chart.py`. Before: `10/11 passed`. After: `11/11 passed`.")
    add("")
    add("## 5. Method (and what was deliberately *not* migrated)")
    add("")
    add("- Every suite was read for its module under test and its imports (`ast`), then mapped")
    add("  to the Go/TS package that owns that surface now. Classification does not require")
    add("  executing the suite: 177 suites cannot execute on this machine for a missing")
    add("  third-party package, and a suite is never called passing unless it ran.")
    add("- `MIGRATE` is used only when a named Go test asserts the same contract (the guard")
    add("  requires `func TestName(` / a quoted `it(\"...\")` title in a repo file).")
    add("- `DEPRECATE` names the owning package and the missing coverage when the Go test set")
    add("  covers only part of the Python guard. Examples of partial coverage that stayed")
    add("  `DEPRECATE` instead of a false `MIGRATE`: the mstat session-aware TTL")
    add("  (`mstat_cache_durability_v1.py` - Go has one 45s TTL), the unitless-never-1e6 rule")
    add("  (`codal_unit_scale_v1090.py`), the board cache invalidation/empty-window controls")
    add("  (`board_hist_cache_v1056.py`), the closing-anchor invariance")
    add("  (`price_basis_v1070.py`), and the notebook derivation of the tape formulas")
    add("  (`tape_filters_v1034.py`).")
    add("- `B` now also covers stdlib-only CI-tooling guards that must keep running (the suite")
    add("  registry, runner profiles, version anchors, Persian glyphs, repo hygiene), which is")
    add("  the controller's ruling for the two new CI-tooling tests.")
    add("- Suites with no Go counterpart (execution/bot/broker/sarkhati, the Python updater,")
    add("  the PyWebView boot page) are `DEPRECATE` with `no replacement: ...` and a named")
    add("  reason, never a fabricated equivalence.")
    add("")
    add("## 6. Full table (one row per registry entry)")
    add("")
    add("| Suite | Category | Disposition | Profile | Go/TS equivalent | Reason | Retirement |")
    add("| --- | --- | --- | --- | --- | --- | --- |")
    for script in sorted(reg):
        e = reg[script]
        eq = e.get("go_equivalent") or e.get("ts_equivalent") or "-"
        add("| `%s` | %s | %s | %s | `%s` | %s | %s |" % (
            script, e["category"], e["disposition"], e["profile"], cell(eq),
            cell(e.get("reason", "")), e.get("retirement_date") or "-"))
    add("")
    add("## 7. Reproduce")
    add("")
    add("```bash")
    add("python dev/suite_registry_guard.py              # SUITE REGISTRY GUARD OK: 258 suites")
    add("python dev/suite_registry_guard.py --selftest   # SELFTEST OK")
    add("python dev/test_suite_registry_guard.py         # SUITE REGISTRY TESTS OK")
    add("python dev/build_python_ci_migration_doc.py --check")
    add("python dev/run_all_tests.py --profile data      # tooling lane")
    add("python dev/run_all_tests.py --profile legacy    # legacy lane (report-only in CI)")
    add("```")
    add("")
    add("The data lane is green for every suite it can execute here except the five")
    add("fixture/oracle suites (B1 board, B2 mstat, B3 chart, B4 fundamental, fundamental")
    add("vectors), whose oracle sections need `fastapi` (see section 4). The legacy lane is")
    add("report-only by design; its red rows are the measured failures above.")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    reg, evidence = load()
    text = build(reg, evidence)
    if args.check:
        current = open(DOC, encoding="utf-8").read() if os.path.isfile(DOC) else ""
        if current != text:
            print("PYTHON CI MIGRATION DOC STALE: run --write")
            return 1
        print("PYTHON CI MIGRATION DOC OK")
        return 0
    if args.write:
        with open(DOC, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print("wrote %s (%d bytes)" % (DOC, len(text.encode("utf-8"))))
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
