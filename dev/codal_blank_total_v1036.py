"""dev/codal_blank_total_v1036.py — سطرِ «جمع»ِ خالی هیچ‌وقت به جزء نمی‌بازد (#177)

چرا: سنجشِ زندهٔ ۱۴ نمادِ تصادفی با کدال دو واگرایی نشان داد و هر دو از یک
جنس بودند. در «وفيروزه» سطرِ «جمع درآمدهای عملیاتی» در خودِ صورتِ مالی **صفر/
خالی** چاپ شده بود؛ پارسر مقدارِ ناصفر نمی‌یافت، کلید را رد می‌کرد و سپس سطرِ
«درآمد سود تضمین‌شده» (۷٬۰۹۶) با رتبۀ ضعیف‌تر برچسبِ «فروش» را می‌گرفت، در
حالی‌که درآمدِ واقعیِ دوره ۶٬۹۳۵٬۴۳۳ بود. یعنی عددی که کاربر در جدول بنیادی
می‌بیند نه کل است نه جزءِ درست، فقط کوچک‌ترین عددِ موجود.

قاعدۀ جزوه که خودِ مالک تأیید کرده (برداشتِ ۱۴): «جمع منتشر نشده ⇒ NULL، هرگز
سطرِ جزء نه». سطرِ خالی هم «منتشرشده» شمار می‌شود.

این گارد رویِ datasourceِ ساخته‌شود می‌دود (بی‌شبکه، بی‌market.db) و سه چیز را
می‌سنجد:
  • جمعِ خالی ⇒ revenue=None و هیچ جزئی جانشینش نمی‌شود
  • جمعِ شماره‌دار ⇒ همان جمع، حتی اگر جزء بزرگ‌تر باشد
  • «جمع درآمدها» (صندوق/سرمایه‌گذاری) ⇒ رتبۀ درست دارد و «سود سهام» را نمی‌گیرد
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from codal_fetcher import parse_tables  # noqa: E402

FAILS = []


def ck(label, cond):
    print(("  ok   " if cond else "  FAIL ") + label)
    if not cond:
        FAILS.append(label)


def ds(rows):
    """یک شیتِ تک‌جدوله با سطرهایی به شکلِ (برچسب، [مقادیر])."""
    cells = []
    for ri, (label, vals) in enumerate(rows, start=1):
        cells.append({"rowSequence": ri, "columnSequence": 1, "value": label})
        for ci, v in enumerate(vals, start=2):
            cells.append({"rowSequence": ri, "columnSequence": ci, "value": v})
    return {"sheets": [{"tables": [{"cells": cells, "description": "کلیه مبالغ به میلیون ریال است"}]}]}


# ۱) وفيروزهٔ واقعی: جمعِ صفر + جزءِ ناصفر
out, rank = {}, {}
parse_tables(ds([
    ("درآمد سود سهام", [6935433, 1776762]),
    ("درآمد سود تضمین شده", [7096, 5764]),
    ("سایر درآمدهای عملیاتی", [20119, 37589]),
    ("جمع درآمدهای عملیاتی", [0, 0]),
    ("سود (زیان) خالص", [0, 0]),
]), out, rank)
ck("جمعِ خالی ⇒ فروش هیچ‌وقت عددِ جزء نمی‌شود", out.get("revenue") is None)
ck("جمعِ خالی ⇒ ردّ برچسب، نه جایگزینیِ جزء (سود خالص هم خالی ماند)", out.get("net_profit") is None)

# ۲) همان شیت با جمعِ شماره‌دار: جمع برنده است هرچه جزء بزرگ‌تر باشد
out2, _ = {}, {}
parse_tables(ds([
    ("درآمد سود سهام", [6935433, 1776762]),
    ("جمع درآمدهای عملیاتی", [4150000, 3758900]),
]), out2)
ck("جمعِ شماره‌دار ⇒ همان جمع، با این‌همه جزءِ بزرگ‌تر", out2.get("revenue") == 4150000)

# ۳) ضمان (صندوق): «جمع درآمدها» باید مچ شود، نه «سود سهام»
out3, _ = {}, {}
parse_tables(ds([
    ("سود (زيان) فروش اوراق بهادار", [-72824, 783833]),
    ("سود سهام", [1065736, 150843]),
    ("سود اوراق بهادار با درآمد ثابت", [1473584, 321171]),
    ("جمع درآمدها", [887059, 4856668]),
]), out3)
ck("«جمع درآمدها»ی صندوق ⇒ ۸۸۷٬۰۵۹ (نه «سود سهام»ِ ۱٬۰۶۵٬۷۳۶)",
   out3.get("revenue") == 887059)

# ۴) شاهدِ منفی: بی‌این اصلاح، خودِ همین شیت واگرایی می‌داد — یعنی گارد
#    قابلیتِ قرمز شدن دارد. (رتبۀ «جمع درآمدها» حذف شود ⇒ جزء برمی‌گردد.)
import codal_fetcher as CF  # noqa: E402
_saved = list(CF.PATTERNS["revenue"])
try:
    CF.PATTERNS["revenue"] = [p for p in _saved if p != r"^جمعدرآمدها$"]
    out4, _ = {}, {}
    parse_tables(ds([
        ("سود سهام", [1065736, 150843]),
        ("جمع درآمدها", [887059, 4856668]),
    ]), out4)
    ck("با حذفِ رتبۀ «جمع درآمدها» گارد باید قرمز شود", out4.get("revenue") != 887059)
finally:
    CF.PATTERNS["revenue"] = _saved

print()
if FAILS:
    print("BLANK-TOTAL GUARD FAILED: %d" % len(FAILS))
    for f in FAILS:
        print("  -", f)
    sys.exit(1)
print("BLANK-TOTAL GUARD OK")
