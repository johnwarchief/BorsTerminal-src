#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""dev/adjust_zero_volume_v1072.py — تعدیل از «بازنویسیِ پایانیِ سطرِ بی‌معامله» هم می‌آید.

چرا این گارد متولد شد (قدمِ ۶ کارِ #73، ۱۴۰۵-۰۷-۱۳). ریشۀ اختلافِ تعدیلِ پیش‌ازِ ۲۰۲۳
حدس نبود، از داده درآمد (`_audit/adjust_zero_volume_probe.py`،
`_audit/parity_event_day_probe.py`، `_audit/ra_parity_report.json`):

  • وبملت بینِ ۲۰۱۱ و ۲۰۱۴ شش تعدیل دارد که زنجیرِ ما هیچ‌کدام را نمی‌دید؛ مقیاسِ
    تاریخِ آن دوره تا ۳٫۸ برابر با رهاورد فرق داشت (خطایِ ثابتِ ۲۷۹٪ → ۱۵٪ درِ شش
    دورۀ پیاپی، و از ۲۰۱۴-۰۷-۲۳ به بعد خطا صفر).
  • علت درِ خودِ CSV خام بود: TSETMC تعدیل را بعضی نمادها داخلِ ستونِ <CLOSE> یکِ
    سطرِ بی‌معامله (VOL=0) می‌گذارد و «قیمت پایه» را دست نمی‌زند:

        2012-02-04  VOL=0  CLOSE=2242  BASE=2242
        2012-02-05  VOL=0  CLOSE=1793  BASE=2242      ← ۱۷۹۳/۲۲۴۲ = ۰٫۷۹۹۷۳
        2012-02-06  VOL=۱۵٬۱۸۷٬۵۸۰  CLOSE=1736  BASE=1793   ← پایه می‌خواند

    قاعدۀ قبلی («گسستِ پایه = تعدیل») رویِ این الگو هیچ‌وقت آتش نمی‌زد.
  • نسبتِ همین سطر با معکوسِ گامِ پلکانِ رهاورد یکی است: ۱/۰٫۷۹۹۷۳ = ۱٫۲۵۰۴ در
    برابرِ ۱٫۲۵۰۴۱۸ِ آن‌ها.
  • پوششِ گام‌هایِ مرجع رویِ ۱۲ نماد: با نشانۀ (ی) تنهایی ۱۷۴/۲۴۷ (۷۰٫۴٪) → با
    (ی)+(ب) ۱۸۸/۲۴۷ (۷۶٫۱٪). درِ همان دوازده نماد، دو نشانۀ روزِ یکی **صفر** بار
    دیده شد، پس جمع‌شدنشان ضریب را دو‌بار نمی‌کند.

این گارد همان قاعدۀ دو‌شاخه را می‌بندد و چهار ضدِ آزمون دارد: روزِ بی‌معاملۀ
معمولی، روزِ معاملۀ معمولی، صندوقِ بی‌لنگر، و فراخوانِ سازگارِ بدونِ `vol`.
بی‌شبکه و بی‌market.dbِ واقعی. اجرا:  python dev/adjust_zero_volume_v1072.py
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import api.chart as CH  # noqa: E402

PASS = FAIL = 0


def ck(ok, what, detail=""):
    global PASS, FAIL
    if ok:
        PASS += 1
        print(f"  ✓ {what}")
    else:
        FAIL += 1
        print(f"  ✗ {what}" + (f"   ← {detail}" if detail else ""))


def rows(*triples):
    """(time, close, base, vol) → همان ساختارِ all_rowsِ خودِ parser."""
    return [{"time": d, "close": c, "base": b, "vol": v} for d, c, b, v in triples]


def ev_of(rs):
    ev, anch = CH._adjust_events_from_rows(rs)
    return ev, anch


CSV_WEBMELT = "\n".join([
    "<TICKER>,<DTYYYYMMDD>,<FIRST>,<HIGH>,<LOW>,<CLOSE>,<VALUE>,<VOL>,<OPENINT>,<PER>,<OPEN>,<LAST>",
    "وبملت,20120206,1748,1754,1710,1736,2.6e13,15187580,0,-22.6,1793,1736",
    "وبملت,20120205,0,0,0,1793,0,0,0,0.0,2242,0",
    "وبملت,20120204,0,0,0,2242,0,0,0,0.0,2242,0",
    "وبملت,20120201,2238,2250,2230,2242,3.1e12,14000000,0,0.2,2230,2242",
])


def main():
    print("— نشاندۀ parser: حجم باید درِ all_rows بماند، وگرنه نشانۀ (ب) کور است")
    cands, vols, all_rows = CH._parse_tsetmc_csv(CSV_WEBMELT)
    ck(all_rows and all("vol" in r for r in all_rows),
       "همۀ ردیف‌هایِ all_rows کلیدِ vol را دارند", str(list(all_rows[0].keys())) if all_rows else "خالی")
    ck(len(cands) == 2, "سطرهایِ بی‌معامله (H=L=۰) کندل نمی‌شوند", f"کندل={len(cands)}")

    print("\n— نشانۀ (ب): بازنویسیِ پایانی رویِ سطرِ بی‌معامله (وبملت ۱۳۹۰-۱۱-۱۶)")
    rs = rows(("2012-02-01", 2242.0, 2230.0, 1.4e7), ("2012-02-04", 2242.0, 2242.0, 0.0),
              ("2012-02-05", 1793.0, 2242.0, 0.0), ("2012-02-06", 1736.0, 1793.0, 1.5e7))
    ev, anch = ev_of(rs)
    ck(anch is True, "درِ لنگر برقرار است و رویدادها رد نمی‌شوند", str(anch))
    ck([e["date"] for e in ev] == ["2012-02-05"], "رویداد درِ همان سطرِ بازنویسی‌شده ثبت می‌شود",
       str(ev))
    ck(ev and abs(ev[0]["ratio"] - 1793.0 / 2242.0) < 1e-6,
       "نسبت = پایانی/پایۀ همان سطر (۰٫۷۹۹۷۳)", str(ev))

    print("\n— نشانۀ (ی): گسستِ قیمتِ پایه (فولاد ۱۴۰۰-۰۳-۰۳) هنوز کار می‌کند")
    rs = rows(("2021-05-23", 12440.0, 12440.0, 0.0), ("2021-05-24", 8870.0, 8870.0, 0.0),
              ("2021-05-25", 8900.0, 8870.0, 6.5e7))
    ev, _ = ev_of(rs)
    ck([e["date"] for e in ev] == ["2021-05-24"], "گسستِ پایه درِ سطرِ بعدی رویداد می‌سازد", str(ev))
    ck(ev and abs(ev[0]["ratio"] - 8870.0 / 12440.0) < 1e-6, "نسبت = پایه/پایانیِ دیروز", str(ev))

    print("\n— ضدِ آزمون ۱: روزِ بی‌معاملۀ معمولی (پایانی == پایه) تعدیل نسازد")
    rs = rows(("2024-06-01", 1453.0, 1450.0, 9.0e6), ("2024-06-02", 1453.0, 1453.0, 0.0),
              ("2024-06-03", 1460.0, 1453.0, 8.0e6))
    ev, _ = ev_of(rs)
    ck(ev == [], "توقفِ بی‌تعدیل هیچ رویدادی نمی‌سازد", str(ev))

    print("\n— ضدِ آزمون ۲: روزِ معاملۀ معمولی (پایانی ≠ پایه، حجمِ مثبت) تعدیل نیست")
    rs = rows(("2024-06-01", 1000.0, 990.0, 5.0e6), ("2024-06-02", 940.0, 1000.0, 4.0e6),
              ("2024-06-03", 950.0, 940.0, 3.0e6))
    ev, _ = ev_of(rs)
    ck(ev == [], "افتِ ۶٪ با حجمِ واقعی رویدادِ تعدیل نیست (پایه به پایانیِ دیروز زنجیر است)", str(ev))

    print("\n— ضدِ آزمون ۳: صندوقِ بی‌لنگر (پایه از NAV می‌آید) همچنان بی‌رویداد")
    rs = [("2026-01-%02d" % i, 100.0 + i, 90.0 + i, 1.0e5) for i in range(1, 31)]
    ev, anch = ev_of(rows(*rs))
    ck(anch is False and ev == [], "درِ لنگر قبلِ هر دو شاخه بسته می‌شود", f"{anch} {ev[:2]}")

    print("\n— ضدِ آزمون ۴: سازگاریِ فراخوانِ بی‌vol (گاردِها/آزمون‌هایِ قدیمی)")
    legacy = [{"time": "2012-02-04", "close": 2242.0, "base": 2242.0},
              {"time": "2012-02-05", "close": 1793.0, "base": 2242.0},
              {"time": "2012-02-06", "close": 1736.0, "base": 1793.0}]
    ev, _ = ev_of(legacy)
    ck(ev == [], "بدونِ کلیدِ vol شاخهٔ (ب) خاموش است و رفتارِ پیشین نمی‌شکند", str(ev))

    print("\n— روزِ مشترک: اگر دو شاخه یکِ روز را بگویند، ضریب **یک‌بار** اعمال شود")
    rs = rows(("2024-01-01", 1000.0, 999.0, 1.0e6),
              ("2024-01-02", 700.0, 800.0, 0.0),      # پایه گسست دارد و پایانی بازنویسی
              ("2024-01-03", 705.0, 700.0, 2.0e6))
    ev, _ = ev_of(rs)
    ck([e["date"] for e in ev] == ["2024-01-02"], "یکِ سطر = یکِ رویداد", str(ev))
    ck(len(ev) == 1 and abs(ev[0]["ratio"] - 800.0 / 1000.0) < 1e-6,
       "نسبتِ گسستِ پایه برمی‌گزیند (نه دو‌بار ضرب)", str(ev))

    print("\n— هندسۀ زنجیر: رویدادها صعودی و یکتا بمانند (فاکتورِ تجمعی به همین وابسته است)")
    rs = rows(("2020-01-01", 1000.0, 1000.0, 1.0e6), ("2020-01-02", 800.0, 1000.0, 0.0),
              ("2020-01-03", 700.0, 800.0, 0.0), ("2020-01-06", 690.0, 700.0, 3.0e6))
    ev, _ = ev_of(rs)
    dates = [e["date"] for e in ev]
    ck(dates == sorted(dates) and len(dates) == len(set(dates)),
       f"دو بازنویسیِ پیاپی = دو رویدادِ صعودی و یکتا", str(ev))

    print(f"\nنتیجه: {PASS} سبز، {FAIL} قرمز")
    return 1 if FAIL else 0


if __name__ == "__main__":
    sys.exit(main())
