// shared/lib/symbolParam.ts -- یکِ قاعدۀِ «نشانی برندهٔ استور» برایِ نماد
//
// چرا اینِ فایل هست: نمادِ دیده‌شدنِ یکِ صفحه ازِ سهِ جا می‌آید (مسیرِ `/x/<symbol>`،
// پาร์امترِ `?symbol=` وِ `useSymbolStore`) وِ هرِ صفحه تاِ امروز یکی از آن‌ها را
// خودش انتخاب می‌کرد. سنجشِ فاز D: `/strategy-tree/فولاد` بی‌سروصدا نمادِ *ذخیره‌شدۀ*
// پیشین را نشان می‌داد، چون خودِ صفحه فقطِ query را می‌خواند. وقتیِ سهِ منبع باِ هم
// می‌جنگند، نتیجگیِ آنِ انتخاب باید یک‌جا نوشته شود وِ آزمونِ واحد داشته باشد --
// وِگرنه هرِ صفحه نسخهٔ خودش را می‌سازد (همانِ مسیری که فاز صفر سه واگراییِ نماد را
// درِ آن ثبت کرد).
//
// ترتیبِ عمدی: مسیر ← پارامتر ← استور. مسیر «همینِ آدرسِ الان» است؛ استور «آخرینِ
// انتخابِ کاربر درِ همینِ دستگاه» وِ بی‌نشانیِ نماد، همانِ استور می‌ماند (صفحه بی‌نماد
// نمی‌شود، فقط آدرس‌پذیر نیست). هیچِ نمادِ پیش‌فرضی اینجا اختراع نمی‌شود: خروجیِ خالی
// یعنی «نمادی نیست» وِ مسئولیتِ فولبکِ نمایشی باِ خودِ صفحه می‌ماند (`viewSymbol`).
const MEANINGLESS = new Set(['-', '--', 'null', 'undefined', 'NaN']);

function clean(v: string | null | undefined): string {
  if (!v) return '';
  let s = String(v).trim();
  // هش‌روتر نمادِ فارسی را percent-encode می‌کند (`%D9%81…`)؛ بدونِ بازخوانی،
  // مقایسه باِ ردیفِ تابلو همیشه باخت می‌داد. `decodeURIComponent` رویِ رشته‌یِ
  // خراب throw می‌کند ⇒ همانِ رشته می‌ماند، نه خالی‌شدنِ بی‌سروصدا.
  if (s.includes('%')) {
    try {
      s = decodeURIComponent(s);
    } catch {
      /* نشانیِ نصفه‌نیمه -- همانِ متن خوانده می‌شود */
    }
  }
  s = s.trim();
  return MEANINGLESS.has(s) ? '' : s;
}

export function resolveSymbolParam(src: {
  path?: string | null;
  query?: string | null;
  stored?: string | null;
}): string {
  return clean(src.path) || clean(src.query) || clean(src.stored);
}
